//! Design tokens: two palettes, the font families, the diagram text sizes, a chart series, the
//! corner radii and the gap.
//!
//! [`Theme::default`] is a complete, open theme, read at build time from the crate's
//! `tokens.toml`. A [`Theme`] deserializes from a table in which
//! every key is optional: what the table leaves out keeps its default, so one line can change one
//! colour.
//!
//! ```
//! use swatchbook::{Mode, Rgb, Theme};
//!
//! let theme: Theme = toml::from_str("[dark]\naccent = \"#ff8800\"\n").expect("valid");
//! assert_eq!(theme.palette(Mode::Dark).accent, Rgb(0xff, 0x88, 0x00));
//! assert_eq!(theme.palette(Mode::Light), Theme::default().palette(Mode::Light));
//! ```

#[cfg(feature = "fonts")]
pub mod fonts;
mod rgb;

/// The defaults, generated by `build.rs` from `tokens.toml`.
mod defaults {
    use super::{Palette, Rgb};

    include!(concat!(env!("OUT_DIR"), "/defaults.rs"));
}

pub use rgb::{ParseRgbError, Rgb};
use serde::Deserialize;

/// Which of the two palettes.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum Mode {
    /// Light text on a dark ground.
    #[default]
    Dark,
    /// Dark text on a light ground.
    Light,
}

/// The colours of one ground.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Palette {
    /// The background.
    pub ground: Rgb,
    /// Body text.
    pub ink: Rgb,
    /// Secondary text, rules, lines.
    pub muted: Rgb,
    /// Headings, markers, highlights.
    pub accent: Rgb,
    /// Panels on the ground (code, boxes).
    pub surface: Rgb,
    /// Edges of panels.
    pub border: Rgb,
    /// Good news, strings.
    pub ok: Rgb,
    /// Attention, numbers, marked text.
    pub warn: Rgb,
    /// Errors.
    pub stop: Rgb,
}

impl Palette {
    /// The default dark palette.
    pub const DARK: Self = defaults::DARK;

    /// The default light palette.
    pub const LIGHT: Self = defaults::LIGHT;

    /// Every token with its name, in declaration order (for templates and previews).
    #[must_use]
    pub const fn named(&self) -> [(&'static str, Rgb); 9] {
        [
            ("ground", self.ground),
            ("ink", self.ink),
            ("muted", self.muted),
            ("accent", self.accent),
            ("surface", self.surface),
            ("border", self.border),
            ("ok", self.ok),
            ("warn", self.warn),
            ("stop", self.stop),
        ]
    }
}

/// The font families a theme sets text in.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Fonts {
    /// Proportional text (diagram labels).
    pub sans: String,
    /// Monospaced text (code, diagrams drawn in a terminal's spirit).
    pub mono: String,
    /// Headings, drawn in the heaviest weight the family has.
    pub display: String,
}

impl Default for Fonts {
    fn default() -> Self {
        Self {
            sans: defaults::SANS.into(),
            mono: defaults::MONO.into(),
            display: defaults::DISPLAY.into(),
        }
    }
}

/// Text sizes in points.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Sizes {
    /// Text in a diagram.
    pub text: f32,
    /// Labels on a diagram's edges.
    pub label: f32,
}

impl Default for Sizes {
    fn default() -> Self {
        Self {
            text: defaults::TEXT,
            label: defaults::LABEL,
        }
    }
}

/// The categorical colours of a chart, in a fixed order: the first series takes the first colour.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Series {
    /// The series on the dark ground.
    pub dark: Vec<Rgb>,
    /// The series on the light ground.
    pub light: Vec<Rgb>,
}

impl Series {
    /// The default dark series.
    pub const DARK: &'static [Rgb] = defaults::SERIES_DARK;

    /// The default light series.
    pub const LIGHT: &'static [Rgb] = defaults::SERIES_LIGHT;

    /// Return the series of `mode`.
    #[must_use]
    pub fn of(&self, mode: Mode) -> &[Rgb] {
        match mode {
            Mode::Dark => &self.dark,
            Mode::Light => &self.light,
        }
    }
}

impl Default for Series {
    fn default() -> Self {
        Self {
            dark: Self::DARK.to_vec(),
            light: Self::LIGHT.to_vec(),
        }
    }
}

/// Corner radii, as CSS lengths (`"4px"`).
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Radii {
    /// A tag or inline code.
    pub sm: String,
    /// A control or a card.
    pub md: String,
    /// A large panel.
    pub lg: String,
}

impl Default for Radii {
    fn default() -> Self {
        Self {
            sm: defaults::RADIUS_SM.into(),
            md: defaults::RADIUS_MD.into(),
            lg: defaults::RADIUS_LG.into(),
        }
    }
}

/// Spacing, as CSS lengths (`"12px"`).
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Space {
    /// A card's padding and the gap between stacked parts.
    pub gap: String,
}

impl Default for Space {
    fn default() -> Self {
        Self {
            gap: defaults::GAP.into(),
        }
    }
}

/// A complete set of tokens.
#[derive(Clone, Debug, PartialEq, Deserialize)]
#[serde(from = "Overlay")]
pub struct Theme {
    /// The dark palette.
    pub dark: Palette,
    /// The light palette.
    pub light: Palette,
    /// The font families.
    pub fonts: Fonts,
    /// The text sizes.
    pub sizes: Sizes,
    /// The chart series.
    pub series: Series,
    /// The corner radii.
    pub radii: Radii,
    /// The spacing.
    pub space: Space,
}

impl Default for Theme {
    fn default() -> Self {
        Self {
            dark: Palette::DARK,
            light: Palette::LIGHT,
            fonts: Fonts::default(),
            sizes: Sizes::default(),
            series: Series::default(),
            radii: Radii::default(),
            space: Space::default(),
        }
    }
}

impl Theme {
    /// Return the palette of `mode`.
    #[must_use]
    pub const fn palette(&self, mode: Mode) -> &Palette {
        match mode {
            Mode::Dark => &self.dark,
            Mode::Light => &self.light,
        }
    }

    /// Return the chart series of `mode`.
    #[must_use]
    pub fn series(&self, mode: Mode) -> &[Rgb] {
        self.series.of(mode)
    }
}

/// A theme as written: every key optional, unknown keys refused.
#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct Overlay {
    #[serde(default)]
    dark: PaletteOverlay,
    #[serde(default)]
    light: PaletteOverlay,
    #[serde(default)]
    fonts: FontsOverlay,
    #[serde(default)]
    sizes: SizesOverlay,
    #[serde(default)]
    series: SeriesOverlay,
    #[serde(default)]
    radii: RadiiOverlay,
    #[serde(default)]
    space: SpaceOverlay,
}

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct PaletteOverlay {
    ground: Option<Rgb>,
    ink: Option<Rgb>,
    muted: Option<Rgb>,
    accent: Option<Rgb>,
    surface: Option<Rgb>,
    border: Option<Rgb>,
    ok: Option<Rgb>,
    warn: Option<Rgb>,
    stop: Option<Rgb>,
}

impl PaletteOverlay {
    fn over(self, base: Palette) -> Palette {
        Palette {
            ground: self.ground.unwrap_or(base.ground),
            ink: self.ink.unwrap_or(base.ink),
            muted: self.muted.unwrap_or(base.muted),
            accent: self.accent.unwrap_or(base.accent),
            surface: self.surface.unwrap_or(base.surface),
            border: self.border.unwrap_or(base.border),
            ok: self.ok.unwrap_or(base.ok),
            warn: self.warn.unwrap_or(base.warn),
            stop: self.stop.unwrap_or(base.stop),
        }
    }
}

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct FontsOverlay {
    sans: Option<String>,
    mono: Option<String>,
    display: Option<String>,
}

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct SizesOverlay {
    text: Option<f32>,
    label: Option<f32>,
}

/// A list replaces the whole default list of its scheme.
#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct SeriesOverlay {
    dark: Option<Vec<Rgb>>,
    light: Option<Vec<Rgb>>,
}

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct RadiiOverlay {
    sm: Option<String>,
    md: Option<String>,
    lg: Option<String>,
}

#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
struct SpaceOverlay {
    gap: Option<String>,
}

impl From<Overlay> for Theme {
    fn from(overlay: Overlay) -> Self {
        let base = Self::default();
        Self {
            dark: overlay.dark.over(base.dark),
            light: overlay.light.over(base.light),
            fonts: Fonts {
                sans: overlay.fonts.sans.unwrap_or(base.fonts.sans),
                mono: overlay.fonts.mono.unwrap_or(base.fonts.mono),
                display: overlay.fonts.display.unwrap_or(base.fonts.display),
            },
            sizes: Sizes {
                text: overlay.sizes.text.unwrap_or(base.sizes.text),
                label: overlay.sizes.label.unwrap_or(base.sizes.label),
            },
            series: Series {
                dark: overlay.series.dark.unwrap_or(base.series.dark),
                light: overlay.series.light.unwrap_or(base.series.light),
            },
            radii: Radii {
                sm: overlay.radii.sm.unwrap_or(base.radii.sm),
                md: overlay.radii.md.unwrap_or(base.radii.md),
                lg: overlay.radii.lg.unwrap_or(base.radii.lg),
            },
            space: Space {
                gap: overlay.space.gap.unwrap_or(base.space.gap),
            },
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_empty_table_is_the_default_theme() {
        let theme: Theme = toml::from_str("").expect("valid");
        assert_eq!(theme, Theme::default());
    }

    #[test]
    fn one_key_changes_one_token() {
        let theme: Theme = toml::from_str(
            "[light]\nink = \"000000\"\n[fonts]\nmono = \"Hack\"\n[sizes]\ntext = 15\n",
        )
        .expect("valid");
        assert_eq!(theme.light.ink, Rgb(0, 0, 0));
        assert_eq!(theme.light.accent, Palette::LIGHT.accent);
        assert_eq!(theme.fonts.mono, "Hack");
        assert_eq!(theme.fonts.sans, "Inter");
        assert_eq!(theme.fonts.display, "Inter");
        assert!((theme.sizes.text - 15.0).abs() < f32::EPSILON);
    }

    #[test]
    fn unknown_keys_and_bad_colours_are_refused() {
        assert!(toml::from_str::<Theme>("[dark]\nacent = \"#000000\"\n").is_err());
        assert!(toml::from_str::<Theme>("[dark]\naccent = \"red\"\n").is_err());
        assert!(toml::from_str::<Theme>("colour = 1\n").is_err());
    }

    #[test]
    fn the_default_palettes_keep_text_readable_on_ground_and_surface() {
        for palette in [Palette::DARK, Palette::LIGHT] {
            for (name, colour) in palette.named() {
                if matches!(name, "ground" | "surface" | "border") {
                    continue;
                }
                for back in [palette.ground, palette.surface] {
                    let ratio = colour.contrast(back);
                    assert!(ratio >= 4.5, "{name} on {back}: contrast {ratio:.2}");
                }
            }
            let label = palette.ground.contrast(palette.accent);
            assert!(label >= 4.5, "ground on accent: contrast {label:.2}");
        }
    }

    #[test]
    fn the_default_series_stand_out_on_ground_and_surface() {
        for mode in [Mode::Dark, Mode::Light] {
            let theme = Theme::default();
            let palette = theme.palette(mode);
            assert_eq!(theme.series(mode).len(), 6);
            for colour in theme.series(mode) {
                for back in [palette.ground, palette.surface] {
                    let ratio = colour.contrast(back);
                    assert!(ratio >= 3.0, "{colour} on {back}: contrast {ratio:.2}");
                }
            }
        }
    }

    /// The crate's copy of the token file.
    const TOKENS: &str = include_str!("../tokens.toml");

    #[test]
    fn the_defaults_are_the_token_file() {
        let table: toml::Table = toml::from_str(TOKENS).expect("valid TOML");
        let keys = |name: &str| table[name].as_table().expect("a table").len();
        assert_eq!((keys("dark"), keys("light")), (9, 9), "every colour is set");
        assert_eq!((keys("fonts"), keys("sizes")), (3, 2));
        assert_eq!((keys("series"), keys("radii"), keys("space")), (2, 3, 1));

        let theme: Theme = toml::from_str(TOKENS).expect("the file loads as a theme");
        assert_eq!(theme, Theme::default());
        assert_eq!(theme.light.muted, Rgb(0x60, 0x6a, 0x7e));
        assert_eq!(theme.radii.md, "8px");
    }

    #[test]
    fn the_copy_matches_the_canonical_file() {
        let canonical = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../../onepage/packages/panelkit/tokens.toml"
        );
        let Ok(text) = std::fs::read_to_string(canonical) else {
            eprintln!("skipped: no onepage checkout next to this one ({canonical})");
            return;
        };
        assert_eq!(
            text, TOKENS,
            "tokens.toml differs from {canonical}; copy it over (see README)"
        );
    }

    #[test]
    fn series_radii_and_space_overlay_like_the_rest() {
        let theme: Theme = toml::from_str(
            "[series]\nlight = [\"#000000\"]\n[radii]\nsm = \"2px\"\n[space]\ngap = \"1rem\"\n",
        )
        .expect("valid");
        assert_eq!(theme.series(Mode::Light), [Rgb(0, 0, 0)]);
        assert_eq!(theme.series(Mode::Dark), Series::DARK);
        assert_eq!(
            (theme.radii.sm.as_str(), theme.radii.md.as_str()),
            ("2px", "8px")
        );
        assert_eq!(theme.space.gap, "1rem");
        assert!(toml::from_str::<Theme>("[radii]\nxl = \"16px\"\n").is_err());
    }
}
