//! Turn `tokens.toml` into the crate's defaults: `$OUT_DIR/defaults.rs`, included by `src/lib.rs`.
//!
//! The file must set every token; a missing or malformed one fails the build.

use std::error::Error;
use std::fmt::Write as _;
use std::path::Path;

type Result<T> = std::result::Result<T, Box<dyn Error>>;

const PALETTE: [&str; 9] = [
    "ground", "ink", "muted", "accent", "surface", "border", "ok", "warn", "stop",
];

fn main() -> Result<()> {
    println!("cargo::rerun-if-changed=tokens.toml");
    let text = std::fs::read_to_string("tokens.toml")?;
    let tokens: toml::Table = text.parse()?;
    let mut out = String::from("// Generated by build.rs from tokens.toml.\n\n");

    for (scheme, name) in [("dark", "DARK"), ("light", "LIGHT")] {
        let table = table(&tokens, scheme)?;
        writeln!(out, "pub(super) const {name}: Palette = Palette {{")?;
        for key in PALETTE {
            writeln!(out, "    {key}: {},", rgb(string(table, scheme, key)?)?)?;
        }
        out.push_str("};\n\n");
    }

    let fonts = table(&tokens, "fonts")?;
    for key in ["sans", "mono", "display"] {
        let value = string(fonts, "fonts", key)?;
        writeln!(
            out,
            "pub(super) const {}: &str = {value:?};",
            key.to_uppercase()
        )?;
    }

    let sizes = table(&tokens, "sizes")?;
    for key in ["text", "label"] {
        let value = match sizes.get(key) {
            Some(toml::Value::Integer(n)) => format!("{n}.0"),
            Some(toml::Value::Float(n)) => format!("{n:?}"),
            _ => return Err(format!("tokens.toml: sizes.{key}: expected a number").into()),
        };
        writeln!(
            out,
            "pub(super) const {}: f32 = {value};",
            key.to_uppercase()
        )?;
    }

    let series = table(&tokens, "series")?;
    for (scheme, name) in [("dark", "SERIES_DARK"), ("light", "SERIES_LIGHT")] {
        let Some(toml::Value::Array(list)) = series.get(scheme) else {
            return Err(format!("tokens.toml: series.{scheme}: expected a list").into());
        };
        let mut items = Vec::new();
        for value in list {
            let toml::Value::String(colour) = value else {
                return Err(format!("tokens.toml: series.{scheme}: expected colours").into());
            };
            items.push(rgb(colour)?);
        }
        writeln!(
            out,
            "pub(super) const {name}: &[Rgb] = &[{}];",
            items.join(", ")
        )?;
    }

    let radii = table(&tokens, "radii")?;
    for key in ["sm", "md", "lg"] {
        let value = string(radii, "radii", key)?;
        writeln!(
            out,
            "pub(super) const RADIUS_{}: &str = {value:?};",
            key.to_uppercase()
        )?;
    }
    let space = table(&tokens, "space")?;
    writeln!(
        out,
        "pub(super) const GAP: &str = {:?};",
        string(space, "space", "gap")?
    )?;

    let dir = std::env::var("OUT_DIR")?;
    std::fs::write(Path::new(&dir).join("defaults.rs"), out)?;
    Ok(())
}

fn table<'a>(tokens: &'a toml::Table, name: &str) -> Result<&'a toml::Table> {
    tokens
        .get(name)
        .and_then(toml::Value::as_table)
        .ok_or_else(|| format!("tokens.toml: [{name}] is missing").into())
}

fn string<'a>(table: &'a toml::Table, name: &str, key: &str) -> Result<&'a str> {
    table
        .get(key)
        .and_then(toml::Value::as_str)
        .ok_or_else(|| format!("tokens.toml: {name}.{key}: expected a string").into())
}

/// `#rrggbb` as the Rust expression `Rgb(0x.., 0x.., 0x..)`.
fn rgb(text: &str) -> Result<String> {
    let hex = text.trim_start_matches('#');
    let bad = || format!("tokens.toml: expected a colour like \"#1d6fb8\", got {text:?}");
    if hex.len() != 6 || !hex.chars().all(|c| c.is_ascii_hexdigit()) {
        return Err(bad().into());
    }
    Ok(format!(
        "Rgb(0x{}, 0x{}, 0x{})",
        &hex[0..2],
        &hex[2..4],
        &hex[4..6]
    ))
}
